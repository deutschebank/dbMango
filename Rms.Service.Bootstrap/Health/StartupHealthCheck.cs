﻿using Microsoft.Extensions.Diagnostics.HealthChecks;

namespace Rms.Service.Bootstrap.Health;

/// <summary>
/// The StartupHealthCheck reports the completion of the long-running startup task and exposes the
/// StartupCompleted property that gets set by the background service
/// </summary>
public class StartupHealthCheck : IHealthCheck
{
    private static volatile bool _isReady;

    /// <summary>
    /// True if startup is complete
    /// </summary>
    public static bool StartupCompleted
    {
        get => _isReady;
        set => _isReady = value;
    }

    public Task<HealthCheckResult> CheckHealthAsync(
        HealthCheckContext context, CancellationToken cancellationToken = default)
    {
        if (StartupCompleted)
        {
            return Task.FromResult(HealthCheckResult.Healthy("The startup task has completed."));
        }

        return Task.FromResult(HealthCheckResult.Unhealthy("That startup task is still running."));
    }
}